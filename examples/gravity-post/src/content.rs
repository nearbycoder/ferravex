//! Authored planets. Terrain samples are forty metres apart; pads flatten their footprints.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Role {
    Depot,
    Pickup,
    Delivery,
    Outpost,
}
impl Role {
    pub fn label(self) -> &'static str {
        match self {
            Self::Depot => "Depot",
            Self::Pickup => "Pickup",
            Self::Delivery => "Deliver",
            Self::Outpost => "Fuel",
        }
    }
}
#[derive(Clone, Copy, Debug, PartialEq)]
